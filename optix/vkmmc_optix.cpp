int main(int argc, char** argv) {
    try {
        CmdOverrides ovr;
        SimConfig cfg;
        SimSetup st;

        if (!vkmmc_frontend(argc, argv, "OptiX", 0, ".ptx", ovr, cfg, st)) {
            return 0;
        }

        if (ovr.listgpu) {
            list_gpus();
            return 0;
        }

        run_simulation(cfg, st, ovr);
    } catch (const std::exception& e) {
        fflush(stdout);
        fprintf(stderr, "vkmmc_optix ERROR: %s\n", e.what());
        return 1;
    }

    return 0;
}

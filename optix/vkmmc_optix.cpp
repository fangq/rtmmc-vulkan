#define CUDA_CHECK(call) do { \
        cudaError_t rc_ = call; \
        if (rc_ != cudaSuccess) { \
            throw std::runtime_error(std::string("CUDA error: ") + cudaGetErrorString(rc_) + " in " + #call); \
        } \
    } while (0)


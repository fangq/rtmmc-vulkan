struct MCParams {
    /* vec4-aligned block (offset 0) */
    float    srcpos[4];                     //  0: vec4
    float    srcdir[4];                     // 16: vec4
    float    srcparam1[4];                  // 32: vec4
    float    srcparam2[4];                  // 48: vec4
    float    nmin[4];                       // 64: vec4  (grid_min)
    float    nmax[4];                       // 80: vec4  (grid_extent)
    uint32_t crop0[4];                      // 96: uvec4 (grid_stride)

    /* scalar block — packed 4 per row (offset 112) */
    float    dstep, tstart, tend, Rtstep;   // 112: 4 floats
    int      srctype, maxgate, outputtype;  // 128: 3 ints
    uint32_t isreflect;                     // 128+12: 1 uint
    uint32_t mediumid0, total_threads;      // 144: 2 uints
    uint32_t num_media, seed;               // 144+8: 2 uints
    uint32_t do_csg, has_curvature;         // 160: 2 uints
    int      threadphoton, oddphoton;       // 160+8: 2 ints
    float    minenergy, roulettesize;       // 176: 2 floats
    uint32_t do_traj, max_traj;             // 184: trajectory flags
    uint32_t photon_base;                   // 192: global photon index offset for this batch
    uint32_t src_num;                       // 196: patterns sharing the photons
    int      src_id;                        // 200: multi-source mode
    uint32_t extra_src_len;                 // 204: sources in the multi-source list
    uint32_t num_field;                     // 208: output fields
    int      focus_mode;                    // 212: see kernel_focus_mode
    uint32_t do_tally;                      // 216: see kernel_tallies_launch
};
// Total: 220 bytes, see the SimParams block in vkmmc_core.comp

